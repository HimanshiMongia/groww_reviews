import os
import smtplib
import markdown
from email.mime.text import MIMEText
from email.mime.multipart import MIMEMultipart
from datetime import datetime
from dotenv import dotenv_values

# Load environment variables from the .env file, with fallback to OS env vars (for GitHub Actions)
env_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'phase2_theme_discovery', '.env')
config = dotenv_values(env_path) if os.path.exists(env_path) else {}

def get_config(key):
    """Get config from .env file first, then fall back to OS environment variables (GitHub Actions)."""
    return config.get(key) or os.environ.get(key)

def load_markdown(filepath):
    """Load the weekly pulse markdown file."""
    if not os.path.exists(filepath):
        raise FileNotFoundError(f"Weekly pulse file not found: {filepath}")
    with open(filepath, 'r', encoding='utf-8') as f:
        return f.read()

