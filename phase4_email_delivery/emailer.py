def send_email(html_content, subject=None):
    """
    Send (or draft) the weekly pulse email via SMTP.
    Uses Gmail SMTP by default. Requires an App Password for Gmail.
    """
    sender_email = get_config("EMAIL_SENDER")
    sender_password = get_config("EMAIL_PASSWORD")
    receiver_email = get_config("EMAIL_RECEIVER")
    
    if sender_email: sender_email = sender_email.strip()
    if sender_password: sender_password = sender_password.strip()
    if receiver_email: receiver_email = receiver_email.strip()
    
    if not sender_email or not sender_password or not receiver_email:
        print("\n[WARNING] Email credentials not configured in .env file.")
        print("To send emails, add the following to your .env:")
        print("  EMAIL_SENDER=your_email@gmail.com")
        print("  EMAIL_PASSWORD=your_app_password")
        print("  EMAIL_RECEIVER=recipient@example.com")
        print("\nSaving the HTML email locally instead...")
        return False
    
    # Generate subject line with week number
    if not subject:
        week_num = datetime.now().isocalendar()[1]
        subject = f"[Weekly Pulse] Groww User Sentiment - Wk {week_num}"
    
    # Create email
    msg = MIMEMultipart('alternative')
    msg['Subject'] = subject
    msg['From'] = sender_email
    msg['To'] = receiver_email
    
    # Attach plain text fallback and the HTML version
    plain_text = "Please view this email in an HTML-compatible email client."
    msg.attach(MIMEText(plain_text, 'plain', 'utf-8'))
    msg.attach(MIMEText(html_content, 'html', 'utf-8'))
    
    try:
        print(f"Connecting to SMTP server...")
        with smtplib.SMTP('smtp.gmail.com', 587) as server:
            server.starttls()
            server.login(sender_email, sender_password)
            server.sendmail(sender_email, receiver_email, msg.as_string())
        print(f"[SUCCESS] Email sent successfully to {receiver_email}!")
        return True
    except Exception as e:
        print(f"[FAILED] Failed to send email: {e}")
        return False

if __name__ == "__main__":
    print("Starting Phase 4: Email Delivery")
    
    # Load the weekly pulse markdown from Phase 3
    pulse_path = os.path.join(os.path.dirname(__file__), "..", "phase3_note_generation", "weekly_pulse.md")
    
    try:
        md_content = load_markdown(pulse_path)
        print("Loaded weekly_pulse.md successfully.")
        
        # Convert markdown to styled HTML
        html_content = markdown_to_html(md_content)
        print("Converted Markdown to HTML email.")
        
        # Save the HTML locally (always, as a backup)
        html_output = os.path.join(os.path.dirname(__file__), "weekly_pulse_email.html")
        with open(html_output, 'w', encoding='utf-8') as f:
            f.write(html_content)
        print(f"Saved HTML email to: {html_output}")
        
        # Attempt to send the email
        email_sent = send_email(html_content)
        
        if not email_sent:
            print(f"\n[INFO] Email was not sent but the HTML file is saved at:\n   {html_output}")
            print("   You can open this file in a browser to preview the email.")
            
    except Exception as e:
        print(f"Fatal error: {e}")
